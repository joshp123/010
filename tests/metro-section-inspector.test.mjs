// Exercise the same scene used by the map. Browser review decides visual quality.
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import * as THREE from '../public/vendor/three/build/three.module.js';
const source=(await readFile(new URL('../public/transit-view.js',import.meta.url),'utf8')).replace("'three'",JSON.stringify(new URL('../public/vendor/three/build/three.module.js',import.meta.url).href));
const {createTransitView}=await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
const view=createTransitView({project:(lat,lon,y=0)=>new THREE.Vector3(lon*111320,2.6+y,-lat*111320)});
view.setMetroData({source:'synthetic test only',segments:[{id:'track',form:'tunnel',coordinates:[[-.002,0],[.002,0]]}]});
const camera=new THREE.OrthographicCamera(-110,110,110,-110,.1,1000);camera.position.set(70,100,70);camera.lookAt(0,0,0);camera.updateMatrixWorld();
view.setView({camera,span:220,viewportHeight:844});
const report={id:'test',mode:'metro',latitude:0,longitude:0,freshness:'fresh',sourceConnected:true,observedAt:1234};
view.update({vehicles:[report]});view.setCutaway(true);
assert.equal(view.getSectionView().integrated,true);
assert.equal(view.getSectionView().viewportHeight,0,'city retains the whole screen');
assert.equal(view.getSectionView().report.observedAt,1234);
assert.equal(view.getSectionGeometry().enabled,true,'source corridor belongs to the city scene');
assert.equal(view.group.getObjectByName('Observed metro').count,1);
assert.ok(view.group.getObjectByName('Cut earth face · depth illustrated'));
view.update({vehicles:[{...report,freshness:'stale'}]});
assert.match(view.statistics().cutawayShortMessage,/not live/);
view.update({vehicles:[]});
assert.equal(view.getSectionView().enabled,false);
assert.equal(view.getSectionGeometry().enabled,false);
assert.equal(view.group.getObjectByName('Observed metro').count,0);
assert.equal(view.statistics().cutawayShortMessage,'No metro report in this section');
view.setCutaway(false);
assert.equal(view.getSectionView().enabled,false);
view.dispose();
console.log('Integrated metro: same city scene, source corridor, current report, stale state and empty-section removal pass.');
