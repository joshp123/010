import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import * as THREE from '../public/vendor/three/build/three.module.js';
const source = (await readFile(new URL('../public/transit-view.js', import.meta.url), 'utf8'))
  .replace("'three'", JSON.stringify(new URL('../public/vendor/three/build/three.module.js', import.meta.url).href));
const { createTransitView } = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
const view = createTransitView({ project: (lat, lon, height = 0) => new THREE.Vector3(lon * 1000, height, lat * 1000) });
view.setMetroData({ source:'synthetic test fixture, never live', segments:[{id:'tunnel',form:'tunnel',coordinates:[[-.1,0],[.1,0]]}] });
const camera = new THREE.OrthographicCamera(-50,50,50,-50,.1,1000);
camera.position.set(0,100,100); camera.lookAt(0,0,0); camera.updateMatrixWorld();
view.setView({camera,span:100,viewportHeight:844});
const metro = Object.freeze({id:'near',mode:'metro',longitude:0,latitude:0,freshness:'fresh',sourceConnected:true});
const farMetro = Object.freeze({...metro,id:'far',longitude:1});
const buses = Array.from({length:100},(_,id)=>Object.freeze({...metro,id:`bus-${id}`,mode:'bus'}));
const snapshot = Object.freeze({vehicles:Object.freeze([metro,farMetro,...buses])});
view.update(snapshot);
view.setCutaway(true);
const mask = view.getCutaway();
function coverageAt(x,z) {
  const {data,width,height}=mask.texture.image, b=mask.bounds;
  const ix=Math.floor((x-b.x)/b.z*width), iy=Math.floor((z-b.y)/b.w*height);
  return ix<0||iy<0||ix>=width||iy>=height?0:data[iy*width+ix];
}
assert.ok(coverageAt(0,12)>128,'opening follows ray from 12m-deep floor to surface');
assert.ok(coverageAt(0,-12)<128,'opposite side of tunnel is not blindly excavated');
const rebuilds=view.statistics().mask.rebuilds;
camera.position.set(100,100,0); camera.lookAt(0,0,0); camera.updateMatrixWorld();
view.setView({camera});
assert.ok(view.statistics().mask.rebuilds>rebuilds,'camera rotation invalidates aperture projection');
let stats = view.statistics();
assert.equal(stats.observations,102);
assert.equal(stats.metroObservations,2);
assert.equal(stats.visibleMetroObservations,1);
assert.equal(stats.visibleFreshUndergroundObservations,1);
assert.equal(stats.underground,1);
assert.equal(stats.metroFocus.id,'near');
assert.equal(stats.section.radiusMetres,38);
const section=view.group.children.find(child=>child.name==='BRT tunnel plan · depth illustrated');
assert.ok(section.children.some(child=>child.name==='Cut earth face · depth illustrated'),'section must contain an actual full-depth earth face');
const sectionPositions=section.children.flatMap(mesh=>Array.from(mesh.geometry.getAttribute('position').array));
assert.ok(sectionPositions.filter((_,i)=>i%3===0).every(x=>Math.abs(x)<=71),'section is bounded around report, not full network');
const older={...metro,freshness:'stale',observedAt:100};
view.update({vehicles:[older,...buses]});
assert.equal(view.statistics().cutawayMessage,'1 older metro report · not live');
assert.equal(view.statistics().metroFocus.freshness,'stale');
view.update({vehicles:[{...metro,sourceConnected:false}]});
assert.equal(view.statistics().cutawayMessage,'1 unverified metro report · not live');
assert.equal(view.statistics().metroFocus,null,'disconnected fresh-looking reports must not become fresh Find targets');
view.update(snapshot);
assert.equal(snapshot.vehicles[0].longitude,0,'do not move reported coordinate to the illustrated track');
view.update({vehicles:buses});
stats=view.statistics();
assert.equal(stats.observations,100);
assert.equal(stats.visibleMetroObservations,0);
assert.equal(stats.cutawayMessage,'No metro report in this section','a busy bus feed must not imply a metro in view');
view.update(snapshot); view.setCutaway(false);
assert.equal(view.statistics().cutawayMessage,null);
const metroBatch=view.group.children.find(child=>child.name==='Observed metro');
assert.equal(metroBatch.count,1,'underground metro is not drawn through accidental ground holes when cutaway is off');
view.dispose();
console.log('Transit classification, viewport counts, report integrity and cutaway visibility tests passed.');

// Regression: long source endpoints sit on a bridge/fallback height while the
// local section is on ordinary ground. Interpolating source endpoint y used to
// put the whole section above the city and its separately projected train.
let localHeight=2;
const elevatedEndpointView=createTransitView({project:(lat,lon,offset=0,context)=>{
  const x=lon*1000,z=lat*1000;
  const ground=context?.preferGround?(Math.abs(x)>80?120:localHeight):60;
  const point=new THREE.Vector3(x,ground+offset,z);
  point.userData={surfaceSource:context?.preferGround?'surveyed ground':'surveyed bridge deck',measured:true};
  return point;
}});
elevatedEndpointView.setMetroData({source:'synthetic height regression, never live',segments:[{id:'long-tunnel',form:'tunnel',coordinates:[[-.25,0],[.25,0]]}]});
camera.position.set(0,102,100);camera.lookAt(0,2,0);camera.updateMatrixWorld();
elevatedEndpointView.setView({camera,span:160,viewportHeight:844});
elevatedEndpointView.update({vehicles:[metro]});elevatedEndpointView.setCutaway(true);
let sectionHeights=elevatedEndpointView.statistics().section;
assert.deepEqual(sectionHeights.surfaceHeightRange,[2,2]);
assert.deepEqual(sectionHeights.floorHeightRange,[-10,-10]);
assert.equal(sectionHeights.report.groundHeight,2,'tunnel report must also bypass bridge deck');
assert.equal(sectionHeights.report.heightDifference,0);
assert.equal(sectionHeights.report.bodyBottomHeight,-9.6);
assert.equal(sectionHeights.geometryBounds.max[1],2,'no section vertex may inherit distant120m endpoint height');
assert.ok(sectionHeights.groundSamples.every(sample=>sample.measured&&sample.surfaceSource==='surveyed ground'));
assert.ok(sectionHeights.groundSamples.length>10,'sample the local section every8m, not just remote endpoints');
localHeight=5;elevatedEndpointView.update({vehicles:[metro]});
sectionHeights=elevatedEndpointView.statistics().section;
assert.deepEqual(sectionHeights.surfaceHeightRange,[5,5]);
assert.equal(sectionHeights.report.heightDifference,0,'surface refresh moves section and report together');
const offsetReport={...metro,latitude:.014};
elevatedEndpointView.update({vehicles:[offsetReport]});
const offsetStats=elevatedEndpointView.statistics();
assert.equal(offsetStats.section.widthMetres,14,'uncertain reporting must not widen whole section');
assert.match(offsetStats.cutawayMessage,/14 m from mapped track/);
assert.equal(elevatedEndpointView.group.children.find(child=>child.name==='Reported metro position · track mismatch').count,1);
assert.equal(elevatedEndpointView.group.children.find(child=>child.name==='Observed metro').count,0,'offset report is not a guessed train on tracks');
elevatedEndpointView.dispose();
console.log('Local surface resampling, bridge exclusion, elevation diagnostics and offset-report tests passed.');
