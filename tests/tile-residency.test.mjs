import assert from 'node:assert/strict';
import { CityTileCache } from '../public/tile-residency.js';
let updates = 0;
const cache = new CityTileCache(() => updates++);
cache.maxBytesSize = 384 * 1024 * 1024;
cache.minBytesSize = cache.maxBytesSize * .8;
const paintedTile = {}, currentCity = {};
cache.add(paintedTile, () => {});
cache.setMemoryUsage(paintedTile, 211 * 1024 * 1024);
cache.setLoaded(paintedTile, true);
cache.add(currentCity, () => {});
cache.setMemoryUsage(currentCity, 174 * 1024 * 1024);
cache.setLoaded(currentCity, true);
cache.markUnused(paintedTile);
cache.unloadUnusedContent();
assert.equal(cache.has(paintedTile), false, 'leaving a large painted atlas must release it even across the retention watermark');
assert.equal(cache.has(currentCity), true, 'visible current city must survive pressure');
assert.equal(cache.isFull(), false);
assert.equal(updates, 1, 'refused traversal must wake after deferred eviction');
assert.equal(cache.pressureEvictions, 1);
const nextTile = {};
assert.equal(cache.add(nextTile, () => {}), true, 'new city requests can resume');
cache.setMemoryUsage(nextTile, 220 * 1024 * 1024);
cache.setLoaded(nextTile, true);
cache.unloadUnusedContent();
assert.equal(cache.has(nextTile), true, 'never evict visible tiles to conceal overcommit');
assert.equal(cache.has(currentCity), true);
console.log('Actual vendored cache path: large stale atlas evicts, active tiles remain, traversal wakes and admits next city.');
